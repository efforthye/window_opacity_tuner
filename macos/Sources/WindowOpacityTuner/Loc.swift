import Foundation

/// The same five string tables as the Windows build (Localization/Loc.cs), with
/// the few lines that describe Windows-only behaviour reworded for macOS.
enum Loc {
    struct Language: Identifiable {
        let tag: String
        let nativeName: String
        let rightToLeft: Bool
        var id: String { tag }
    }

    static let languages: [Language] = [
        Language(tag: "en", nativeName: "English", rightToLeft: false),
        Language(tag: "ko", nativeName: "한국어", rightToLeft: false),
        Language(tag: "ja", nativeName: "日本語", rightToLeft: false),
        Language(tag: "zh", nativeName: "简体中文", rightToLeft: false),
        Language(tag: "ar", nativeName: "العربية", rightToLeft: true),
    ]

    static func isRightToLeft(_ tag: String) -> Bool {
        languages.first { $0.tag == tag }?.rightToLeft ?? false
    }

    /// Looks up a key, falling back to English and then to the key itself.
    /// `{0}`, `{1}`… are replaced by `args`, as in the Windows build.
    static func t(_ key: String, _ lang: String, _ args: CustomStringConvertible...) -> String {
        format(key, lang, args)
    }

    static func format(_ key: String, _ lang: String, _ args: [CustomStringConvertible]) -> String {
        var s = tables[lang]?[key] ?? tables["en"]?[key] ?? key
        for (i, a) in args.enumerated() {
            s = s.replacingOccurrences(of: "{\(i)}", with: a.description)
        }
        return s
    }

